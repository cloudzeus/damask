import { describe, it, expect } from 'vitest'
import { speakable, groupDigits } from '@/lib/voice/speakable'

describe('speakable', () => {
  it('τηλέφωνα ψηφίο-ψηφίο ανά 3', () => {
    expect(speakable('Καλέστε 6940960701')).toBe('Καλέστε έξι εννιά τέσσερα, μηδέν εννιά έξι, μηδέν εφτά μηδέν ένα')
    expect(groupDigits('2107218758')).toEqual(['210', '721', '8758'])
  })
  it('ΑΦΜ ένα-ένα ψηφίο και ακρωνύμια ολόκληρα', () => {
    expect(speakable('ΑΦΜ 094183948')).toBe('Αριθμός Φορολογικού Μητρώου μηδέν εννιά τέσσερα ένα οχτώ τρία εννιά τέσσερα οχτώ')
    expect(speakable('Το ΕΣΠΑ ζητά ΕΜΕ και ΚΑΔ.')).toBe('Το Εταιρικό Σύμφωνο για το Πλαίσιο Ανάπτυξης ζητά Ετήσιες Μονάδες Εργασίας και Κωδικός Αριθμός Δραστηριότητας.')
    expect(speakable('ΑΕΡΟΔΡΟΜΙΟ')).toBe('αεροδρομιο')
  })
  it('κεφαλαία επωνυμίες και συντομογραφίες με τελείες', () => {
    expect(speakable('η «ΚΙΒΩΤΟΠΟΥΛΟΣ ΜΟΝΟΠΡΟΣΩΠΗ Α.Ε.»')).toBe('η «κιβωτοπουλος μονοπροσωπη Ανώνυμη Εταιρεία»')
    expect(speakable('ΠΑΠΑΔΟΠΟΥΛΟΣ Α.Ε και ΚΩΣΤΑΣ Α.Ε. εδώ')).toBe('παπαδοπουλος Ανώνυμη Εταιρεία και κωστας Ανώνυμη Εταιρεία εδώ')
    expect(speakable('DGSOFT Ι.Κ.Ε. και ΟΑΕΔ')).toBe('DGSOFT Ιδιωτική Κεφαλαιουχική Εταιρεία και ΟΑΕΔ')
  })
  it('ποσά, έτη και σύνδεσμοι', () => {
    expect(speakable('€12.500 και 1.250,50 το 2024')).toBe('€12.500 και 1.250,50 το 2024')
    expect(speakable('δες [την καρτέλα](/partners/x)')).toBe('δες την καρτέλα')
  })
})
