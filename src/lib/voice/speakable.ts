const DIGIT = ['μηδέν', 'ένα', 'δύο', 'τρία', 'τέσσερα', 'πέντε', 'έξι', 'εφτά', 'οχτώ', 'εννιά']
const words = (digits: string) => digits.split('').map(d => DIGIT[Number(d)]).join(' ')

