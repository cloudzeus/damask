/** ΚΕΦΑΛΑΙΑ (≥5 γράμματα, όχι γνωστό ακρωνύμιο) → πεζά με τελικό ς. Πιο σύντομα (π.χ. ΟΑΕΔ) μένουν να συλλαβίζονται. */
function decap(text: string): string {
  return text.replace(/(?<![\p{L}])[\p{Lu}][\p{Lu}\p{M}]{4,}(?![\p{L}])/gu, w => {
    if (ACR_MAP.has(w) || !/[\u0370-\u03ff]/.test(w)) return w
    return w.toLocaleLowerCase('el').replace(/σ(?![\p{L}])/gu, 'ς')
  })
}

const esc = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
const ACR_RE = new RegExp(`(?<![\\p{L}\\d])(${ACRONYMS.map(([a]) => esc(a)).join('|')})(?![\\p{L}\\d])`, 'gu')
const ACR_MAP = new Map(ACRONYMS.map(([a, b]) => [a, b]))

/** 3-3-…-4: ένα μονοψήφιο υπόλοιπο κολλά στην τελευταία ομάδα (694 096 0701). */
export function groupDigits(digits: string): string[] {
  const groups = digits.match(/.{1,3}/g) ?? [digits]
  if (groups.length > 1 && groups[groups.length - 1].length === 1) groups.splice(-2, 2, groups.slice(-2).join(''))
  return groups
}

export function speakable(text: string): string {
  const out = text
    .replace(/\*\*(.+?)\*\*/g, '$1')
    .replace(/\[([^\]]+)\]\([^)]+\)/g, '$1')
    .replace(/(?<![\d.,])\+?\d(?:[\d \-]{5,}\d)(?![\d.,])/g, m => {
      const digits = m.replace(/\D/g, '')
      if (digits.length < 7) return m
      if (digits.length === 9) return words(digits) // ΑΦΜ: ένα-ένα ψηφίο
      return groupDigits(digits).map(words).join(', ')
    })

  return decap(DOTTED.reduce((acc, [re, to]) => acc.replace(re, to), out).replace(ACR_RE, a => ACR_MAP.get(a) ?? a))
}
