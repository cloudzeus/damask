/** Σειριοποίηση των δεδομένων προγράμματος σε συμπαγές context για το μοντέλο. */
export function buildProgramCmsUserMessage(data: Record<string, unknown>): string {
  return [
    'Δεδομένα προγράμματος (από αποδελτίωση):',
    '```json',
    JSON.stringify(data, null, 2),
    '```',
    '',
    'Παρήγαγε το CMS JSON με το παραπάνω σχήμα. Απάντησε ΜΟΝΟ με το JSON.',
  ].join('\n')
}
